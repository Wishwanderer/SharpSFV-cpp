#!/usr/bin/env python3
# Part of the SharpSFV C++ port (GPL-3.0). Test tooling.
"""Builds the test corpus used by compare_with_oracle.sh.

Creates a directory tree with awkward file names and sizes, checksum files full of edge
cases (BOMs, odd spacing, comments, bad lines), filter cases and INI variants.
Usage: make_corpus.py <output dir>
"""
import hashlib
import os
import random
import sys
import zlib

root = sys.argv[1]
rnd = random.Random(1234)


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def rbytes(n):
    return bytes(rnd.getrandbits(8) for _ in range(n)) if n < 200000 else os.urandom(n)


data = os.path.join(root, "data")
# Sizes around the 16-byte CRC slicing boundary, xxHash3 internal block sizes and the
# 50 MB "large file" threshold.
sizes = [0, 1, 3, 15, 16, 17, 64, 128, 129, 240, 241, 1023, 1024, 1025, 65536, 1048579]
for i, n in enumerate(sizes):
    write(os.path.join(data, f"size_{n:07d}.bin"), rbytes(n))
write(os.path.join(data, "big", "large_60mb.bin"), os.urandom(60 * 1024 * 1024 + 7))

names = ["space name.txt", "UPPER.TXT", "paren (1).txt", "unicode_é_中文_😀.txt", "dots.in.name.tar.gz",
         "semi;colon.txt", "hash#mark.txt", "no_ext", "a.iso", "b.mkv", "c.nfo"]
for n in names:
    write(os.path.join(data, n), n.encode() * 3)
for d in ["sub1", "sub2", os.path.join("sub1", "deep"), os.path.join("sub1", "deep", "deeper"), "zz_last"]:
    for k in range(3):
        write(os.path.join(data, d, f"f{k}.dat"), rbytes(100 + k))
# Hidden (dot) entries and a symlink are skipped by the enumeration on Unix.
write(os.path.join(data, ".hidden_file"), b"hidden")
write(os.path.join(data, ".hidden_dir", "inside.txt"), b"hidden")
try:
    os.symlink(os.path.join(data, "UPPER.TXT"), os.path.join(data, "link_to_upper.txt"))
    os.symlink(os.path.join(data, "sub2"), os.path.join(data, "link_dir"))
except OSError:
    pass

# ---------------------------------------------------------------- checksum files
ck = os.path.join(root, "checksums")
os.makedirs(ck, exist_ok=True)


def crc_be(b):
    return f"{zlib.crc32(b) & 0xffffffff:08X}"


def file_bytes(rel):
    with open(os.path.join(data, rel), "rb") as f:
        return f.read()


rels = ["size_0000017.bin", "space name.txt", "unicode_é_中文_😀.txt", os.path.join("sub1", "f0.dat"), "UPPER.TXT"]

# Classic SFV from another tool (big-endian CRC, name first), with one corrupt and one missing.
lines = ["; Generated by QuickSFV v2.36", "; comment with ; inside", ""]
for r in rels:
    lines.append(f"{r} {crc_be(file_bytes(r))}")
lines.append("size_0000016.bin 00000000")       # BAD
lines.append("missing_file.bin DEADBEEF")       # MISSING
lines.append("   leading_space.bin 12345678")   # parse: leading spaces
lines.append("tabs\there.bin\t\tCAFEBABE  ")     # tabs
lines.append("ninehex 123456789")               # not an SFV line (9 hex)
lines.append("CBF43926 *hashfirst.bin")         # hash-first inside .sfv
write(os.path.join(data, "standard.sfv"), "\r\n".join(lines).encode() + b"\r\n")

# Mixed byte orders in one file: standard (QuickSFV-style) and reversed (C# SharpSFV-style).
mixed = []
for i, r in enumerate(rels):
    be = crc_be(file_bytes(r))
    mixed.append(f"{r} {be if i % 2 == 0 else be[6:8] + be[4:6] + be[2:4] + be[0:2]}")
write(os.path.join(data, "mixed_order.sfv"), "\r\n".join(mixed).encode() + b"\r\n")

# MD5 with mixed styles, BOM, comments that the UI shows, odd hex, lower case.
md5 = ["// Shown comment 1 ", "//Shown comment 2", "; hidden comment"]
for r in rels:
    md5.append(f"{hashlib.md5(file_bytes(r)).hexdigest()} *{r}")
md5.append(f"{hashlib.md5(file_bytes('UPPER.TXT')).hexdigest().upper()}  UPPER.TXT")  # two spaces, text mode
md5.append("ABC *odd_length.bin")           # odd length -> skipped
md5.append("abc def")                        # 'abc' is hex: odd -> skipped
md5.append("abcd def")                       # parses: hash ABCD, file 'def' (MISSING)
md5.append("nothex *file")                   # no match
md5.append("0123456789abcdef0123456789abcdef *")  # empty file name
md5.append(" d41d8cd98f00b204e9800998ecf8427e *size_0000000.bin ")  # NBSP as whitespace
write(os.path.join(data, "mixed.md5"), b"\xef\xbb\xbf" + "\n".join(md5).encode())

# UTF-16 LE with BOM, CR-only line endings.
sha1 = [f"{hashlib.sha1(file_bytes(r)).hexdigest()} *{r}" for r in rels]
write(os.path.join(data, "utf16.sha1"), b"\xff\xfe" + "\r".join(sha1).encode("utf-16-le"))

sha256 = [f"{hashlib.sha256(file_bytes(r)).hexdigest()} {r}" for r in rels]
write(os.path.join(data, "plain.sha256"), "\n".join(sha256).encode())

# .txt -> algorithm comes from the fallback argument
write(os.path.join(data, "list.txt"), "\n".join(md5[3:8]).encode())

# Parse-only stress file
stress = []
for i in range(400):
    pad = rnd.choice(["", " ", "  ", "\t", " \t "])
    star = rnd.choice(["", "*", " *", "**"])
    h = "".join(rnd.choice("0123456789abcdefABCDEF") for _ in range(rnd.choice([7, 8, 9, 31, 32, 40, 64])))
    nm = rnd.choice(["a.bin", "dir/x y.bin", "  spaced  ", "", "ünï.txt", "CBF43926", "x 12345678"])
    style = rnd.random()
    if style < 0.5:
        stress.append(f"{pad}{h}{pad or ' '}{star}{nm}{pad}")
    elif style < 0.9:
        stress.append(f"{pad}{nm}{pad or ' '}{h}{pad}")
    else:
        stress.append(rnd.choice(["", "   ", "//c " + nm, ";x", "[section]", h, nm]))
write(os.path.join(ck, "stress.txt"), "\n".join(stress).encode())

# ---------------------------------------------------------------- filter cases
masks = []
fnames = ["a.iso", "A.ISO", "movie.mkv", "notes.txt", "data1.dat", "data12.dat", "x(1).txt", "x.y.z", "readme",
          "pic.JPEG", "a+b.txt", "[x].txt", "$var.txt", "^caret.txt", "tab.txt"]
pats = ["", "*.iso", "*.ISO;*.mkv", "*.txt, *.nfo", "data?.dat", "*.*", "*", "x(?).txt", "*.y.*", "read*",
        "[x].*", "$var.*", "^caret*", "a+b*", " ; ", ";;", "*.jpeg", "*e*", "?????", "*.t?t"]
for f in fnames:
    for inc in pats:
        for exc in ["", "*.txt", "data*", "*.ISO"]:
            masks.append(f"{f}\t{inc}\t{exc}")
write(os.path.join(ck, "masks.tsv"), "\n".join(masks).encode())

# ---------------------------------------------------------------- INI files
inis = {
    "default.ini": "",
    "full.ini": "[SharpSFV]\r\nTimeTab=1\r\nShowThroughputStats=1\r\nPathStorageMode=Absolute\r\nUseAbsolutePaths=1\r\n"
                "ShowFilterPanel=1\r\nShowAdvancedBar=1\r\nEnableChecksumComments=1\r\nPathPrefix=incoming\\iso\\\r\n"
                "IncludePattern=*.iso;*.mkv\r\nExcludePattern=*.nfo\r\nScanRecursive=0\r\nProcessingMode=SSD\r\n"
                "ShowFullPaths=1\r\nShowHashCol=0\r\nShowExpectedHashCol=0\r\nLockColumns=0\r\n"
                "ColumnOrder=Name:0,Hash:2,Status:1\r\nSignature=Me\r\nDefaultAlgo=SHA256\r\nWindowSizeW=1024\r\n"
                "WindowSizeH=700\r\nWindowPosX=-5\r\nWindowPosY=40\r\nSplitterPos=120\r\n",
    "weird.ini": "﻿  timetab = 1 \nPROCESSINGMODE=hdd\nprocessingmode=2\nDefaultAlgo= crc32 \nDefaultAlgo=bogus\n"
                 "OptimizeForHDD=1\nWindowSizeW=abc\nWindowSizeH= +77 \nWindowPosX=10\nSplitterPos=x\n"
                 "ColumnOrder=Name:2,,Hash:x,Bad,Status:1,Name:0,a:b:c\n=novalue\nnoequals\n[Other]\n"
                 "Signature=a=b=c\nPathStorageMode=1\nUseAbsolutePaths=0\n",
}
for n, c in inis.items():
    write(os.path.join(ck, n), c.encode("utf-8"))
print(root)
