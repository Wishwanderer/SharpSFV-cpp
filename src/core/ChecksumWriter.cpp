#include "ChecksumWriter.h"

#include "FileSystem.h"
#include "PathUtil.h"

namespace sfv {

namespace {

void WriteHeader(fs::TextWriter& w, const AppSettings& s, HashType algo, bool jobMode) {
    if (!s.enableChecksumComments) return;
    if (jobMode)
        w.WriteLine("; Generated by SharpSFV (Job Mode)");
    else
        w.WriteLine("; Generated by SharpSFV (Signature: " + s.customSignature + ")");
    w.WriteLine(std::string("; Algorithm: ") + ToString(algo));
}

std::string ApplyPrefix(const AppSettings& s, std::string p) {
    if (s.showAdvancedBar && !s.pathPrefix.empty()) return path::Combine(s.pathPrefix, p);
    return p;
}

} // namespace

bool WriteSaveAs(const std::string& outPath, const FileStore& store, const AppSettings& settings, HashType algo,
                 std::string* error) {
    const std::string saveDirectory = path::GetDirectoryName(outPath).value_or("");
    fs::TextWriter w;
    if (!w.Open(outPath, error)) return false;
    WriteHeader(w, settings, algo, false);

    const int count = store.Count();
    for (int i = 0; i < count; ++i) {
        if (store.IsSummaryRow(i)) continue;
        const ItemStatus status = store.Status(i);
        const std::string hash = store.GetCalculatedHashString(i, settings.crc32ByteOrder);
        if (hash.empty() || status == ItemStatus::Queued || status == ItemStatus::Pending) continue;

        const std::string fullPath = store.GetFullPath(i);
        std::string pathToWrite = fullPath;
        if (settings.pathStorageMode == PathStorageMode::Relative) {
            if (auto rel = path::GetRelativePath(saveDirectory, fullPath)) {
                if (path::IsPathRooted(*rel) && !rel->starts_with('.'))
                    pathToWrite = store.RelativePath(i); // different drive: fall back to the stored relative path
                else
                    pathToWrite = *rel;
            }
        }
        w.WriteLine(hash + " *" + ApplyPrefix(settings, pathToWrite));
    }
    return w.Close(error);
}

bool WriteCreateMode(const std::string& outPath, const FileStore& store, const AppSettings& settings, HashType algo,
                     std::string* error) {
    // The C# version always wrote the path relative to the common folder of the selection,
    // which only verifies when the file is saved in that folder (the dialog's default). Paths
    // are written relative to the file's own folder instead; in the default case that is the
    // same text. A file on another drive keeps the selection-relative path.
    const std::string saveDirectory = path::GetDirectoryName(outPath).value_or("");
    fs::TextWriter w;
    if (!w.Open(outPath, error)) return false;
    WriteHeader(w, settings, algo, false);

    const int count = store.Count();
    for (int i = 0; i < count; ++i) {
        if (store.IsSummaryRow(i)) continue;
        const std::string hash = store.GetCalculatedHashString(i, settings.crc32ByteOrder);
        if (hash.empty()) continue;
        std::string pathToWrite = store.RelativePath(i);
        if (auto rel = path::GetRelativePath(saveDirectory, store.GetFullPath(i)); rel && !path::IsPathRooted(*rel))
            pathToWrite = *rel;
        w.WriteLine(hash + " *" + pathToWrite);
    }
    return w.Close(error);
}

bool WriteJobFile(const std::string& outPath, const FileStore& store, const AppSettings& settings, HashType algo) {
    fs::TextWriter w;
    if (!w.Open(outPath)) return true;
    WriteHeader(w, settings, algo, true);
    const std::string outDir = path::GetDirectoryName(outPath).value_or("");

    int errorCount = 0;
    const int count = store.Count();
    for (int i = 0; i < count; ++i) {
        if (store.IsSummaryRow(i)) continue;
        const ItemStatus status = store.Status(i);
        if (status == ItemStatus::Error || status == ItemStatus::Bad) ++errorCount;

        const std::string hash = store.GetCalculatedHashString(i, settings.crc32ByteOrder);
        if (status != ItemStatus::OK || hash.empty()) continue;

        const std::string fileFullPath = store.GetFullPath(i);
        std::string pathToWrite = path::GetRelativePath(outDir, fileFullPath).value_or(fileFullPath);
        w.WriteLine(hash + " *" + ApplyPrefix(settings, pathToWrite));
    }
    if (!w.Close()) return true;
    return errorCount > 0;
}

} // namespace sfv
